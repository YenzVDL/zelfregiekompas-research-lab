import { test, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";

test("LIVE pilot fixes: planned scenarios, research preflight, three methods and saved-output Evaluation", async ({ page, request }) => {
  test.setTimeout(360000);
  const generator = "llama3.2:3b", evaluator = "gemma3:4b";
  const models = await (await request.get("/api/models")).json();
  test.skip(![generator,evaluator].every((name) => models.models.some((m: any) => m.name === name)), "Exact local llama3.2:3b and gemma3:4b required; no substitute or simulated execution");
  const post = async (url: string, data: any) => {const r = await request.post(url,{data}); expect(r.ok(), await r.text()).toBe(true); return r.json();};
  const token=Date.now();
  const dataset=await post('/api/datasets',{name:'LIVE varied pilot software verification '+token});
  await page.goto('/');
  await page.getByRole('button',{name:'Scenarios',exact:true}).click();
  await page.getByRole('combobox',{name:'Dataset',exact:true}).selectOption(dataset.id);
  await page.getByRole('button',{name:'Generate locally',exact:true}).click();
  await expect(page.getByText('ICT topics',{exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'Local model',exact:true}).selectOption(evaluator);
  await page.getByRole('spinbutton',{name:'Count',exact:true}).fill('3');
  await page.getByText('Custom distribution',{exact:true}).click();
  const distribution=[{topic:'databases and SQL',variation:'partial completion',count:1},{topic:'programming and algorithms',variation:'completed with understanding',count:1},{topic:'web development and APIs',variation:'missing information',count:1}];
  await page.getByRole('textbox',{name:'Scenario distribution JSON',exact:true}).fill(JSON.stringify(distribution));
  const queued=page.waitForResponse((r) => r.url().endsWith('/scenario-tasks/generation') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Queue generation',exact:true}).click();
  const generation=await (await queued).json();
  await expect.poll(async () => ['completed','failed','cancelled','interrupted'].includes((await (await request.get('/api/jobs/'+generation.id)).json()).status),{timeout:180000,intervals:[500,1000]}).toBe(true);
  const generated=await (await request.get('/api/jobs/'+generation.id)).json();
  expect(generated.status,generated.error).toBe('completed');
  expect(generated.results).toHaveLength(3);
  const scenarios=await (await request.get('/api/scenarios?dataset_id='+dataset.id)).json();
  expect(new Set(scenarios.map((s: any) => s.generation.plan_item.topic)).size).toBe(3);
  expect(new Set(scenarios.map((s: any) => s.inputs.learning_goal)).size).toBe(3);
  expect(Object.keys(generated.generation_summary.actual_topic_coverage)).toEqual(expect.arrayContaining(['databases and SQL','programming and algorithms','web development and APIs']));
  for (const scenario of scenarios) {
    expect(scenario.review_status).toBe('awaiting_review');
    expect(scenario.generation.request.payload.prompt).toContain(scenario.generation.plan_item.topic);
    if (scenario.generation.plan_item.variation==='missing information') expect(scenario.inputs.progress).toBeNull();
    if (scenario.generation.plan_item.variation==='partial completion') expect(scenario.inputs.progress.completed_units).toBeLessThan(scenario.inputs.progress.planned_units);
    if (scenario.generation.plan_item.variation==='completed with understanding') expect(scenario.inputs.control_results.some((c: any) => c.question && c.student_answer && c.recorded_assessment.toLowerCase()==='correct')).toBe(true);
    // Isolated software acceptance only; this does not approve research material.
    await post(`/api/scenarios/${scenario.id}/review`,{decision:'approved',reviewer:'software-verification-fixture',feedback:'Isolated software acceptance fixture, not educational validation or production human approval'});
  }
  const ds=await post('/api/snapshots',{kind:'dataset',dataset_id:dataset.id,name:'LIVE varied development snapshot '+token});
  const bank=await post('/api/banks',{name:'LIVE evidence applicability fixtures '+token});
  const addQuestion=async (text: string, conditions: any, priority: number) => post('/api/questions',{bank_id:bank.id,text,conditions,priority,origin:'MANUALLY AUTHORED SOFTWARE ACCEPTANCE FIXTURE'});
  await addQuestion('What would you like to reflect on about this learning activity?',{},0);
  await addQuestion('What could you learn from the difference between your completed and planned units?',{compare:[{left:'progress.completed_units',op:'lt',right:'progress.planned_units'}]},10);
  await addQuestion('Which approach helped you check your understanding of the control answer?',{control_assessment:'correct'},10);
  await addQuestion('What progress information would help you reflect on this activity?',{missing:['progress']},15);
  await addQuestion('Which SQL query approach would help you reflect on joins?',{present:['learning_goal']},1);
  const bs=await post('/api/snapshots',{kind:'bank',bank_id:bank.id,review_mode:'experimental',name:'LIVE experimental applicability bank '+token});
  const diagnostic=await (await request.get(`/api/banks/${bank.id}/diagnostics?bank_snapshot_id=${bs.id}&dataset_snapshot_id=${ds.id}`)).json();
  expect(diagnostic.development_cases).toBe(3);
  await page.reload();
  await page.getByRole('button',{name:'Experiments',exact:true}).click();
  const experimentName='LIVE compatible pilot comparison '+token;
  await page.getByRole('textbox',{name:'Experiment name',exact:true}).fill(experimentName);
  await page.getByRole('combobox',{name:'Dataset snapshot',exact:true}).selectOption(ds.id);
  await page.getByRole('combobox',{name:'Question-bank snapshot',exact:true}).selectOption(bs.id);
  await page.getByRole('checkbox',{name:/Retrieval-augmented generation/}).check();
  await page.getByRole('checkbox',{name:/Constrained LLM/}).check();
  if (models.models.some((m: any) => m.name==='qwen3:4b' && m.identity.variant==='thinking-only')) {
    await page.getByRole('checkbox',{name:/qwen3:4b /}).check();
    await expect(page.getByRole('button',{name:'Queue experiment →',exact:true})).toBeDisabled();
    await expect(page.getByText(/Selected artifact is thinking-only/)).toBeVisible();
    await page.getByRole('checkbox',{name:/qwen3:4b /}).uncheck();
  }
  await page.getByRole('checkbox',{name:/llama3.2:3b /}).check();
  const pfResponse=page.waitForResponse((r) => r.url().endsWith('/experiments/preflight') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Run research preflight',exact:true}).click();
  const preflight=await (await pfResponse).json();
  expect(preflight.passed,JSON.stringify(preflight.checks)).toBe(true);
  const expResponse=page.waitForResponse((r) => r.url().endsWith('/experiments') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Queue experiment →',exact:true}).click();
  const experiment=await (await expResponse).json();
  await expect.poll(async () => (await (await request.get('/api/jobs/'+experiment.id)).json()).status,{timeout:120000}).toBe('completed');
  const outputs=await (await request.get('/api/outputs?job_id='+experiment.id)).json();
  expect(outputs).toHaveLength(9);
  for (const method of ['fixed','rag','constrained']) expect(outputs.some((o: any) => o.method===method && o.status==='completed')).toBe(true);
  expect(outputs.filter((o: any) => o.method!=='fixed').every((o: any) => o.actual_request?.payload.options.num_predict===128 && o.actual_request.payload.think===false)).toBe(true);
  const preserved=JSON.stringify(outputs);
  await page.getByRole('button',{name:'Evaluation',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Evaluation',exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'Experiment to evaluate',exact:true}).selectOption(experiment.id);
  await page.getByRole('combobox',{name:'Local evaluator for saved outputs',exact:true}).selectOption(evaluator);
  const eligible=outputs.filter((o: any) => o.status==='completed').length;
  await expect(page.getByText(new RegExp(`^${eligible} eligible ·`))).toBeVisible();
  const evalResponse=page.waitForResponse((r) => r.url().endsWith('/evaluation/jobs') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Evaluate with local model',exact:true}).click();
  const evaluation=await (await evalResponse).json();
  await expect.poll(async () => ['completed','completed_with_errors','failed','cancelled'].includes((await (await request.get('/api/jobs/'+evaluation.id)).json()).status),{timeout:150000}).toBe(true);
  const finalEvaluation=await (await request.get('/api/jobs/'+evaluation.id)).json();
  expect(finalEvaluation.assessed_count).toBeGreaterThan(0);
  expect(finalEvaluation.assessed_count+(finalEvaluation.failed_count||0)+(finalEvaluation.skipped_count||0)).toBe(eligible);
  expect(JSON.stringify(await (await request.get('/api/outputs?job_id='+experiment.id)).json())).toBe(preserved);
  const assessments=await (await request.get('/api/evaluation/attempts?job_id='+evaluation.id)).json();
  for (const a of assessments) {expect(Object.keys(JSON.parse(a.prompt)).sort()).toEqual(['reflection_question','scenario_inputs']); expect(a.model_metadata.digest).toBe(models.models.find((m: any) => m.name===evaluator).digest);}
  const metrics=await (await request.get(`/api/jobs/${experiment.id}/metrics`)).json();
  expect(metrics.quality.human.overall.end_to_end_acceptance).toBeNull();
  expect(metrics.evaluator_accuracy.correctness.macro_f1).toBeNull();
  await page.screenshot({path:'../docs/pilot-evaluation-live.png',fullPage:true});
  const labelsBefore=await (await request.get('/api/labels')).json();
  await page.getByText('Evaluator calibration on controlled development examples',{exact:true}).click();
  const calibrationResponse=page.waitForResponse((r) => r.url().endsWith('/evaluation/calibrate') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Run evaluator calibration',exact:true}).click();
  const calibration=await (await calibrationResponse).json();
  expect(calibration.checks).toHaveLength(6);
  expect((await (await request.get('/api/labels')).json()).length).toBe(labelsBefore.length);
  await writeFile('../docs/pilot-fixes-live-verification.json',JSON.stringify({evidence:'Actual local Ollama and application UI/endpoints, isolated software verification database; no model fixtures or production approvals',models,generation:generated,scenarios,diagnostic,preflight,experiment,outputs,evaluation:finalEvaluation,assessments,metrics,calibration},null,2));
});
