import { test, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";

test("independent bank CRUD and experimental snapshot controls", async ({ page, request }) => {
  const token = Date.now().toString();
  await page.goto("/");
  await page.getByRole("button", { name: "Question bank", exact: true }).click();
  await page.getByRole("button", { name: "+ New bank", exact: true }).click();
  await page.getByRole("textbox", { name: "Bank name", exact: true }).fill("Browser isolated bank " + token);
  await page.getByRole("textbox", { name: "Bank description", exact: true }).fill("TEST FIXTURE: independent collection");
  await page.getByRole("button", { name: "Create bank", exact: true }).click();
  const selector = page.getByRole("combobox", { name: "Question bank", exact: true });
  await expect(selector).toContainText("Browser isolated bank " + token);
  await expect(selector).not.toHaveValue("bank_legacy_default");
  const bankId = await selector.inputValue();
  await page.getByRole("textbox", { name: "Question and applicability (JSON)", exact: true }).fill(JSON.stringify({
    text: "What would you like to reflect on about your learning approach?", tags: ["strategy"], conditions: {}, priority: 0, origin: "BROWSER FIXTURE",
  }));
  await page.getByRole("button", { name: "Create question for review", exact: true }).click();
  await expect(page.locator("button.list-item")).toHaveCount(1);
  await selector.selectOption("bank_legacy_default");
  await expect(page.getByRole("button", { name: /What would you like to reflect on about your learning approach/ })).toHaveCount(0);
  await selector.selectOption(bankId);
  await expect(page.locator("button.list-item")).toHaveCount(1);
  let generationRequests = 0;
  page.on("request", (r) => { if (r.method() === "POST" && /\/banks\/[^/]+\/generate$/.test(r.url())) generationRequests++; });
  await page.getByRole("button", { name: "Generate questions", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Local bank question model", exact: true })).toBeVisible();
  expect(generationRequests).toBe(0);
  await page.getByRole("button", { name: "Snapshots", exact: true }).click();
  await page.getByRole("combobox", { name: "Snapshot type", exact: true }).selectOption("bank");
  await page.getByRole("textbox", { name: "Snapshot name", exact: true }).fill("Experimental browser bank " + token);
  await page.getByRole("button", { name: "Freeze approved versions", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("No approved latest versions");
  await page.getByRole("combobox", { name: "Bank snapshot review mode", exact: true }).selectOption("experimental");
  await page.getByRole("button", { name: "Freeze experimental bank", exact: true }).click();
  await expect(page.getByRole("cell").filter({ hasText: "Experimental browser bank " + token })).toContainText("EXPERIMENTAL");
  const snapshots = await (await request.get("/api/snapshots")).json();
  const snapshot = snapshots.find((s: any) => s.name === "Experimental browser bank " + token);
  expect(snapshot.bank_id).toBe(bankId);
  expect(snapshot.records[0].review_status).toBe("awaiting_review");
  await page.getByRole("button", { name: "Experiments", exact: true }).click();
  await page.getByRole("combobox", { name: "Question-bank snapshot", exact: true }).selectOption(snapshot.id);
  await expect(page.getByText(/EXPERIMENTAL BANK —/)).toBeVisible();
  await page.getByRole("combobox", { name: "Split", exact: true }).selectOption("test");
  await expect(page.getByRole("button", { name: "Queue experiment →", exact: true })).toBeDisabled();
  await page.getByRole("checkbox", { name: /Fixed question bank/ }).uncheck();
  await page.getByRole("checkbox", { name: /Constrained LLM/ }).check();
  await expect(page.getByRole("combobox", { name: "Question-bank snapshot", exact: true })).toBeDisabled();
  await expect(page.getByText(/EXPERIMENTAL BANK —/)).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Queue experiment →", exact: true })).toBeEnabled();
});

test("LIVE Ollama: generate into a selected bank, inspect exact request, freeze and run experimental development", async ({ page, request }) => {
  const localModel = process.env.BANK_LIVE_MODEL || "gemma3:4b";
  const modelState = await (await request.get("/api/models")).json();
  test.skip(!modelState.models?.some((m: any) => m.name === localModel), `Local ${localModel} unavailable; no fallback model or successful bank generation is simulated`);
  test.setTimeout(180000);
  const token = Date.now().toString();
  await page.goto("/");
  await page.getByRole("button", { name: "Question bank", exact: true }).click();
  await page.getByRole("button", { name: "+ New bank", exact: true }).click();
  await page.getByRole("textbox", { name: "Bank name", exact: true }).fill("LIVE local reflection bank " + token);
  await page.getByRole("button", { name: "Create bank", exact: true }).click();
  const bankSelector = page.getByRole("combobox", { name: "Question bank", exact: true });
  await expect(bankSelector.locator("option:checked")).toHaveText("LIVE local reflection bank " + token);
  const bankId = await bankSelector.inputValue();
  await page.getByRole("button", { name: "Generate questions", exact: true }).click();
  await page.getByRole("combobox", { name: "Local bank question model", exact: true }).selectOption(localModel);
  await page.getByRole("spinbutton", { name: "Number of questions", exact: true }).fill("2");
  await page.getByRole("textbox", { name: "Additional instructions (optional)", exact: true }).fill("Create two distinct, reusable questions. Both must be unconditional fallback questions: present=[], missing=[], contains={}. Use open wording about the learner's approach or next steps.");
  const queued = page.waitForResponse((response) => /\/banks\/[^/]+\/generate$/.test(response.url()) && response.request().method() === "POST");
  await page.getByRole("button", { name: "Queue question generation", exact: true }).click();
  const job = await (await queued).json();
  expect(job.bank_id).toBe(bankId);
  await expect.poll(async () => ["completed", "completed_with_errors", "failed", "cancelled", "interrupted"].includes((await (await request.get(`/api/jobs/${job.id}`)).json()).status), { timeout: 140000, intervals: [500, 1000] }).toBe(true);
  const final = await (await request.get(`/api/jobs/${job.id}`)).json();
  expect(final.status, final.error).toBe("completed");
  const questions = await (await request.get(`/api/questions?bank_id=${bankId}`)).json();
  expect(questions).toHaveLength(2);
  expect(questions.every((q: any) => q.bank_id === bankId && q.review_status === "awaiting_review")).toBe(true);
  expect(questions.every((q: any) => q.generation.request.capture_source === "httpx request immediately before send")).toBe(true);
  expect(questions.every((q: any) => q.generation.model_metadata.digest === modelState.models.find((m: any) => m.name === localModel).digest)).toBe(true);
  await expect(page.locator("button.list-item")).toHaveCount(2, { timeout: 10000 });
  await page.locator("button.list-item").filter({ hasText: questions[0].question_id }).click();
  const details = page.locator("details").filter({ has: page.locator("summary", { hasText: /^View generation prompt$/ }) });
  await details.locator("summary").click();
  await expect(details.locator("pre").nth(0)).toHaveText(questions[0].generation.request.payload.system);
  await expect(details.locator("pre").nth(1)).toHaveText(questions[0].generation.request.payload.prompt);
  await expect(details.getByText(/Installed digest:/)).toContainText(questions[0].generation.model_metadata.digest);
  await page.screenshot({ path: "../docs/browser-live-question-bank.png", fullPage: true });

  const regular = await request.post("/api/snapshots", { data: { kind: "bank", bank_id: bankId, name: "Must require approval" } });
  expect(regular.status()).toBe(422);
  const snapshot = await (await request.post("/api/snapshots", { data: { kind: "bank", bank_id: bankId, name: "LIVE experimental generated bank", review_mode: "experimental" } })).json();
  expect(snapshot.usable_fallback).toBe(true);
  const dataset = await (await request.post("/api/datasets", { data: { name: "LIVE fixed-bank software verification" } })).json();
  const scenario = await (await request.post("/api/scenarios", { data: { dataset_id: dataset.id, row: { inputs: { learning_goal: "Understand Python functions", planned_activity: "Write and test a Python function" }, synthetic_origin: "MANUALLY AUTHORED SOFTWARE-TEST FIXTURE" } } })).json();
  await request.post(`/api/scenarios/${scenario.id}/review`, { data: { decision: "approved", reviewer: "software-verification-fixture", feedback: "Software acceptance fixture, not educational validation" } });
  const ds = await (await request.post("/api/snapshots", { data: { kind: "dataset", dataset_id: dataset.id, name: "LIVE fixed development fixture" } })).json();
  const experiment = await (await request.post("/api/experiments", { data: { name: "LIVE generated-bank fixed development run", dataset_snapshot_id: ds.id, bank_snapshot_id: snapshot.id, split: "development", methods: ["fixed"], ai_control: false } })).json();
  await expect.poll(async () => (await (await request.get(`/api/jobs/${experiment.id}`)).json()).status).toBe("completed");
  const outputs = await (await request.get(`/api/outputs?job_id=${experiment.id}`)).json();
  expect(outputs[0].status).toBe("completed");
  expect(outputs[0].model).toBeNull();
  expect(outputs[0].bank_snapshot).toEqual(experiment.bank_snapshot);
  expect(outputs[0].bank_snapshot.review_mode).toBe("experimental");
  expect(questions.some((q: any) => q.id === outputs[0].trace.selected_version_id)).toBe(true);
  const exported = await (await request.get(`/api/jobs/${experiment.id}/export`)).json();
  expect(exported.bank_snapshot_identity.content_hash).toBe(snapshot.content_hash);
  // Real completed job can leave the main list without losing its records.
  await page.reload(); // Experiment above was queued through the HTTP API.
  await page.getByRole("button", { name: "Experiments", exact: true }).click();
  const experimentCard = page.locator(".job").filter({ hasText: experiment.id });
  await expect(experimentCard).toBeVisible();
  await experimentCard.getByRole("button", { name: "Archive job", exact: true }).click();
  await expect(experimentCard).toHaveCount(0);
  await page.getByRole("checkbox", { name: /Archived jobs/ }).check();
  await page.getByRole("textbox", { name: "Find job", exact: true }).fill(experiment.id);
  await expect(experimentCard).toBeVisible();
  expect((await (await request.get(`/api/jobs/${experiment.id}/export`)).json()).outputs).toHaveLength(1);
  await page.reload();
  await page.getByRole("button", { name: "Experiments", exact: true }).click();
  await page.getByRole("checkbox", { name: /Archived jobs/ }).check();
  await page.getByRole("textbox", { name: "Find job", exact: true }).fill(experiment.id);
  await expect(experimentCard).toBeVisible();
  await experimentCard.getByRole("button", { name: "Restore job", exact: true }).click();
  await expect(experimentCard).toHaveCount(0);
  await page.getByRole("checkbox", { name: /Archived jobs/ }).uncheck();
  await expect(experimentCard).toBeVisible();
  await writeFile("../docs/question-bank-live-verification.json", JSON.stringify({ evidence: "Real local Ollama generation, real application endpoints and browser; no model fixtures", generation_job: final, questions, experimental_snapshot: snapshot, experiment, outputs, exported }, null, 2));
});
